// Copies the compiled BatchRegistry ABI into the backend so both stay in sync.
const fs = require("fs");
const path = require("path");
const artifact = require("../artifacts/contracts/BatchRegistry.sol/BatchRegistry.json");
const target = path.join(__dirname, "..", "..", "apps", "backend", "src", "modules", "blockchain", "abi.ts");
fs.writeFileSync(
  target,
  `// Auto-generated by blockchain/scripts/export-abi.js. Do not edit by hand.\nexport const BatchRegistryABI = ${JSON.stringify(artifact.abi, null, 2)};\n`,
);
console.log(`ABI written to ${target}`);
